/**
 * Phase 4.4: AI assessment routes, mounted at /api/ai. Every route requires login (middleware/auth.js).
 *
 * Express is the only public gateway and the only writer of CLAIM_RISK_ASSESSMENT, PROVIDER_RISK_PROFILE and
 * CLAIM_INVESTIGATION_OUTCOME. The ML service (FastAPI, internal, X-ML-API-Key) only computes, on a read-only session.
 *
 * Rules (see ml_service/docs/PHASE4_ARCHITECTURE.md):
 *  - The model is resolved by MODEL_KEY (never a hard-coded MODEL_ID) and must be registered, active, approved for
 *    live application data and of the same version the ML service reports. Otherwise nothing is stored.
 *  - Append-only snapshots: a new assessment is stored only when its INDICATORS_DIGEST differs from the claim's latest
 *    NON-FAILED assessment (CLAIM_LATEST_VALID_ASSESSMENT); otherwise that stored assessment is returned. Failed calls
 *    are stored as 'failed' rows, which are never the baseline. Nothing is ever updated or deleted.
 *  - Timestamps (ASSESSED_AT, COMPUTED_AT, DECIDED_AT) are generated by MySQL (UTC); Express never sends one and
 *    always returns the stored value read back from the database.
 *  - Outcomes must name the exact snapshot (assessment_id) the investigator was shown. It is validated here and by the
 *    database trigger trg_cio_valid_snapshot; no other snapshot is ever substituted.
 *  - AI output never changes CLAIM.STATUS, never approves or rejects a claim. If the ML service is unavailable the
 *    response says so; no assessment is invented. Existing routes do not depend on anything here.
 *  - Research endpoints describe the public Kaggle (US Medicare) dataset only and are never applied to application data.
 */
'use strict';
const express = require('express');
const auth = require('../middleware/auth');
const requireRole = require('../middleware/requireRole');
const { createMlClient, MlUnavailableError, MlRequestError } = require('../services/mlClient');
const { createAiRateLimits } = require('../middleware/aiRateLimit');

const { ROLES } = requireRole;
const OUTCOMES = ['Confirmed Fraud', 'Legitimate', 'Requires Further Investigation'];
const OUTCOME_BASES = ['documentary_evidence', 'investigator_judgement', 'external_finding', 'other'];
const PRIORITIES = ['Routine', 'Elevated', 'High'];
const DIGEST_RE = /^[0-9a-f]{64}$/;
const KAGGLE_ID_RE = /^PRV\d{5}$/;
const FIGURE_RE = /^[a-z_]{1,40}$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const TIMESTAMP_FIELDS = ['decided_at', 'DECIDED_AT', 'assessed_at', 'ASSESSED_AT', 'computed_at', 'COMPUTED_AT'];
const MAX_ERROR = 500;
const NOT_STORED_REASONS = new Set(['disabled', 'not_configured', 'circuit_open']);  // no call was made
// Application date policy: "today" = calendar date in IST (UTC+05:30, no DST) on the MySQL server clock.
// Independent of the Node host's and the MySQL session's time zone. Mirrors ml_service/app_risk/dates.py.
const APP_UTC_OFFSET_MINUTES = 330;
const APP_TODAY_SQL = `SELECT DATE_FORMAT(UTC_TIMESTAMP() + INTERVAL ${APP_UTC_OFFSET_MINUTES} MINUTE, '%Y-%m-%d') AS d`;
const UNAVAILABLE_MESSAGE ='AI assessment unavailable. The existing rule-based fraud detection is unaffected.';

class HttpError extends Error {
  constructor(status, message, extra = {}) {
    super(message);
    this.status = status;
    this.extra = extra;
  }
}

const parseId = (v, what) => {
  const n = Number(v);
  if (!/^\d+$/.test(String(v)) || !Number.isSafeInteger(n) || n < 1 || n > 2147483647) {
    throw new HttpError(400, `Invalid ${what} ID`);
  }
  return n;
};

const truncate = (s) => String(s).slice(0, MAX_ERROR);

/** DB row -> API object. Dates come back from mysql2 as Date (pool timezone +00:00) and serialise as ISO 8601 UTC ("Z"). */
const formatAssessment = (r) => r && ({
  assessment_id: r.ASSESSMENT_ID,
  claim_id: r.CLAIM_ID,
  model_key: r.MODEL_KEY,
  indicator_set_version: r.INDICATOR_SET_VERSION,
  assessment_status: r.ASSESSMENT_STATUS,
  snapshot_claim_count: r.SNAPSHOT_CLAIM_COUNT,
  indicators_digest: r.INDICATORS_DIGEST,
  rule_hits: r.RULE_HITS,
  indicators: r.INDICATORS,
  triggered_count: r.TRIGGERED_COUNT,
  review_priority: r.REVIEW_PRIORITY,
  priority_reasons: r.PRIORITY_REASONS,
  error_message: r.ERROR_MESSAGE,
  trigger_source: r.TRIGGER_SOURCE,
  requested_by_user_id: r.REQUESTED_BY_USER_ID,
  assessed_at: r.ASSESSED_AT,
});

const formatProfile = (r) => r && ({
  profile_id: r.PROFILE_ID,
  provider_id: r.PROVIDER_ID,
  model_key: r.MODEL_KEY,
  profile_status: r.PROFILE_STATUS,
  as_of_date: r.AS_OF_DATE_TEXT,
  claim_count: r.CLAIM_COUNT,
  indicators: r.INDICATORS,
  error_message: r.ERROR_MESSAGE,
  computed_at: r.COMPUTED_AT,
});

const formatOutcome = (r) => r && ({
  outcome_id: r.OUTCOME_ID,
  claim_id: r.CLAIM_ID,
  outcome: r.OUTCOME,
  outcome_basis: r.OUTCOME_BASIS,
  notes: r.NOTES,
  decided_by: { user_id: r.DECIDED_BY_USER_ID, email: r.DECIDED_BY_EMAIL, role: r.DECIDED_BY_ROLE },
  assessment_id: r.ASSESSMENT_ID,
  decided_at: r.DECIDED_AT,
  training: r.EXCLUSION_REASON === undefined ? undefined : {
    eligible: Boolean(r.IS_TRAINING_ELIGIBLE),
    exclusion_reason: r.EXCLUSION_REASON,
  },
});

const ASSESSMENT_SELECT = `SELECT a.*, m.MODEL_KEY FROM CLAIM_RISK_ASSESSMENT a JOIN MODEL_REGISTRY m ON m.MODEL_ID = a.MODEL_ID`;
const PROFILE_SELECT = `SELECT p.*, DATE_FORMAT(p.AS_OF_DATE, '%Y-%m-%d') AS AS_OF_DATE_TEXT, m.MODEL_KEY
                        FROM PROVIDER_RISK_PROFILE p JOIN MODEL_REGISTRY m ON m.MODEL_ID = p.MODEL_ID`;

/** Minimal structural check of the ML service's claim assessment before anything is stored. */
function validateClaimAssessment(b, claimId) {
  const ok = b && b.kind === 'claim_level_indicators' && b.claim_id === claimId
    && typeof b.indicator_set === 'string' && typeof b.indicator_set_version === 'string'
    && ['completed', 'insufficient_data'].includes(b.assessment_status)
    && Number.isInteger(b.snapshot_claim_count) && DIGEST_RE.test(b.indicators_digest || '')
    && Array.isArray(b.rule_hits) && Array.isArray(b.indicators) && Number.isInteger(b.triggered_count)
    && PRIORITIES.includes(b.review_priority) && Array.isArray(b.priority_reasons);
  if (!ok) throw new MlUnavailableError('bad_response', 'AI service returned an assessment in an unexpected format');
}

function validateProviderProfile(b, providerId) {
  const ok = b && b.kind === 'provider_level_indicators' && b.provider_id === providerId
    && typeof b.indicator_set === 'string' && typeof b.indicator_set_version === 'string'
    && ['completed', 'insufficient_data'].includes(b.profile_status) && DATE_RE.test(b.as_of_date || '')
    && Number.isInteger(b.claim_count) && Array.isArray(b.indicators);
  if (!ok) throw new MlUnavailableError('bad_response', 'AI service returned a provider profile in an unexpected format');
}

function createAiRouter({ pool = require('../config/db'), ml = createMlClient.fromEnv(),
  indicatorSetKey = process.env.ML_INDICATOR_SET_KEY || 'app-indicators-v2', limits = createAiRateLimits() } = {}) {
  const router = express.Router();
  router.use(auth);   // every AI endpoint requires a valid JWT
  // Rate limits (middleware/aiRateLimit.js): per user, after authentication and role checks; 429 when exceeded.
  const COMPUTE = [limits.compute, limits.computeGlobal];

  const wrap = (fn) => async (req, res) => {
    try {
      await fn(req, res);
    } catch (err) {
      if (err instanceof HttpError) return res.status(err.status).json({ success: false, message: err.message, ...err.extra });
      console.error('[ai]', err && err.message);
      return res.status(500).json({ success: false, message: 'Internal server error' });
    }
  };

  /** Registry lookup by MODEL_KEY. Returns the row, or throws if it may not be used for live assessments. */
  async function resolveModel(conn, key, reportedVersion) {
    const [[m]] = await conn.query(
      'SELECT MODEL_ID, MODEL_KEY, MODEL_KIND, VERSION, APPLIES_TO_LIVE_DATA, IS_ACTIVE FROM MODEL_REGISTRY WHERE MODEL_KEY = ?', [key]);
    if (!m) throw new HttpError(503, `Indicator set '${key}' is not registered in MODEL_REGISTRY; nothing was stored`, { ai_status: 'unavailable', reason: 'model_not_registered' });
    if (m.MODEL_KIND !== 'app_indicator_set' || m.APPLIES_TO_LIVE_DATA !== 1 || m.IS_ACTIVE !== 1) {
      throw new HttpError(503, `Registered model '${key}' is not an active indicator set approved for live data; nothing was stored`,
        { ai_status: 'unavailable', reason: 'model_not_approved' });
    }
    if (reportedVersion !== undefined && reportedVersion !== m.VERSION) {
      throw new HttpError(503, `AI service reports version ${reportedVersion} but '${key}' is registered as ${m.VERSION}; nothing was stored`,
        { ai_status: 'unavailable', reason: 'model_version_mismatch' });
    }
    return m;
  }

  /** Record a failed attempt (only after a real call failed). Never the digest baseline. Returns its id or null. */
  async function recordFailedAssessment(claimId, err, source, userId) {
    try {
      const [[m]] = await pool.query(
        'SELECT MODEL_ID FROM MODEL_REGISTRY WHERE MODEL_KEY = ? AND APPLIES_TO_LIVE_DATA = 1', [indicatorSetKey]);
      if (!m) return null;
      const [r] = await pool.query(
        `INSERT INTO CLAIM_RISK_ASSESSMENT (CLAIM_ID, MODEL_ID, ASSESSMENT_STATUS, ERROR_MESSAGE, TRIGGER_SOURCE, REQUESTED_BY_USER_ID)
         VALUES (?, ?, 'failed', ?, ?, ?)`,
        [claimId, m.MODEL_ID, truncate(`${err.reason || 'error'}: ${err.message}`), source, userId ?? null]);
      return r.insertId;
    } catch (e) {
      console.error('[ai] could not record failed assessment:', e.message);
      return null;
    }
  }

  async function latestValidAssessment(claimId) {
    const [[row]] = await pool.query(
      `SELECT v.*, m.MODEL_KEY FROM CLAIM_LATEST_VALID_ASSESSMENT v JOIN MODEL_REGISTRY m ON m.MODEL_ID = v.MODEL_ID WHERE v.CLAIM_ID = ?`, [claimId]);
    return row || null;
  }

  async function requireClaim(claimId) {
    const [[c]] = await pool.query('SELECT CLAIM_ID FROM CLAIM WHERE CLAIM_ID = ?', [claimId]);
    if (!c) throw new HttpError(404, 'Claim not found');
  }

  /** Compute via the ML service, then store a new snapshot only if the digest changed. */
  async function assessClaim(claimId, source, user) {
    let body;
    try {
      body = await ml.getJson(`/v1/claims/${claimId}/indicators`);
      validateClaimAssessment(body, claimId);
    } catch (err) {
      if (err instanceof MlRequestError) {
        throw new HttpError(err.status === 404 ? 404 : 400, err.status === 404 ? 'Claim not found by the AI service' : 'Invalid claim ID');
      }
      if (!(err instanceof MlUnavailableError)) throw err;
      const failedId = NOT_STORED_REASONS.has(err.reason) ? null : await recordFailedAssessment(claimId, err, source, user.id);
      const last = await latestValidAssessment(claimId);
      throw new HttpError(503, UNAVAILABLE_MESSAGE, {
        ai_status: 'unavailable', reason: err.reason, failed_attempt_id: failedId,
        last_valid_assessment: last ? { ...formatAssessment(last), stale: true } : null,
      });
    }

    const conn = await pool.getConnection();
    const lockName = `fraud_ai_assessment_${claimId}`;
    let locked = false;
    try {
      const [[{ got }]] = await conn.query('SELECT GET_LOCK(?, 5) AS got', [lockName]);
      if (got !== 1) throw new HttpError(503, 'Assessment busy, please retry', { ai_status: 'busy' });
      locked = true;
      let model;
      try {
        model = await resolveModel(conn, body.indicator_set, body.indicator_set_version);
      } catch (e) {
        if (e instanceof HttpError) {
          const failedId = await recordFailedAssessment(claimId, { reason: e.extra.reason, message: e.message }, source, user.id);
          e.extra.failed_attempt_id = failedId;
        }
        throw e;
      }
      const [[base]] = await conn.query(
        'SELECT ASSESSMENT_ID, INDICATORS_DIGEST FROM CLAIM_LATEST_VALID_ASSESSMENT WHERE CLAIM_ID = ?', [claimId]);
      let id;
      let snapshot;
      if (base && base.INDICATORS_DIGEST === body.indicators_digest) {
        id = base.ASSESSMENT_ID;
        snapshot = 'unchanged';
      } else {
        const [r] = await conn.query(
          `INSERT INTO CLAIM_RISK_ASSESSMENT (CLAIM_ID, MODEL_ID, ASSESSMENT_STATUS, INDICATOR_SET_VERSION, SNAPSHOT_CLAIM_COUNT,
             INDICATORS_DIGEST, RULE_HITS, INDICATORS, TRIGGERED_COUNT, REVIEW_PRIORITY, PRIORITY_REASONS, TRIGGER_SOURCE, REQUESTED_BY_USER_ID)
           VALUES (?, ?, ?, ?, ?, ?, CAST(? AS JSON), CAST(? AS JSON), ?, ?, CAST(? AS JSON), ?, ?)`,
          [claimId, model.MODEL_ID, body.assessment_status, body.indicator_set_version, body.snapshot_claim_count,
            body.indicators_digest, JSON.stringify(body.rule_hits), JSON.stringify(body.indicators), body.triggered_count,
            body.review_priority, JSON.stringify(body.priority_reasons), source, user.id ?? null]);
        id = r.insertId;
        snapshot = 'new';
      }
      const [[stored]] = await conn.query(`${ASSESSMENT_SELECT} WHERE a.ASSESSMENT_ID = ?`, [id]);   // read back: DB timestamp
      return {
        success: true,
        ai_status: 'available',
        snapshot,
        assessment: formatAssessment(stored),
        current_computation: {                    // provenance of this check (not part of the digest)
          snapshot_taken_at: body.snapshot_taken_at,
          snapshot_claim_count: body.snapshot_claim_count,
          prior_history_claim_count: body.prior_history_claim_count,
          digest_scope: body.digest_scope,
        },
        disclaimer: body.disclaimer,
      };
    } finally {
      if (locked) await conn.query('SELECT RELEASE_LOCK(?)', [lockName]).catch(() => {});
      conn.release();
    }
  }

  // ── Service status ───────────────────────────────────────────
  router.get('/status', limits.read, wrap(async (req, res) => {
    const client = ml.status();
    let service = { reachable: false };
    try {
      const s = await ml.getJson('/v1/status');
      service = { reachable: true, version: s.version, indicator_set: s.indicator_set, indicator_set_version: s.indicator_set_version,
        application_database: s.application_database, research_available: s.research_available };
    } catch (err) {
      service = { reachable: false, reason: err.reason || 'error' };
    }
    const [[m]] = await pool.query(
      'SELECT MODEL_ID, MODEL_KEY, VERSION, MODEL_KIND, APPLIES_TO_LIVE_DATA, IS_ACTIVE FROM MODEL_REGISTRY WHERE MODEL_KEY = ?', [indicatorSetKey]);
    const registry = m
      ? { model_key: m.MODEL_KEY, version: m.VERSION, registered: true,
        approved_for_live_data: m.APPLIES_TO_LIVE_DATA === 1 && m.MODEL_KIND === 'app_indicator_set', active: m.IS_ACTIVE === 1 }
      : { model_key: indicatorSetKey, registered: false };
    const consistent = Boolean(m && service.reachable && service.indicator_set === m.MODEL_KEY && service.indicator_set_version === m.VERSION);
    res.json({ success: true, ml_enabled: client.enabled, ml_configured: client.configured, timeout_ms: client.timeout_ms, rate_limits: limits.config,
      circuit: client.circuit, ml_service: service, registry, ready: consistent && registry.approved_for_live_data && registry.active });
  }));

  // ── Claim assessments ───────────────────────────────────────
  router.get('/claims/:id/assessment', ...COMPUTE, wrap(async (req, res) => {
    const claimId = parseId(req.params.id, 'claim');
    await requireClaim(claimId);
    res.json(await assessClaim(claimId, 'on_view', req.user));
  }));

  router.post('/claims/:id/assessment', requireRole(ROLES.INVESTIGATION), limits.recompute, limits.computeGlobal, wrap(async (req, res) => {
    const claimId = parseId(req.params.id, 'claim');
    await requireClaim(claimId);
    res.json(await assessClaim(claimId, 'manual_recompute', req.user));
  }));

  router.get('/claims/:id/assessments', limits.read, wrap(async (req, res) => {   // append-only history, newest first
    const claimId = parseId(req.params.id, 'claim');
    await requireClaim(claimId);
    const [rows] = await pool.query(`${ASSESSMENT_SELECT} WHERE a.CLAIM_ID = ? ORDER BY a.ASSESSED_AT DESC, a.ASSESSMENT_ID DESC LIMIT 100`, [claimId]);
    res.json({ success: true, data: rows.map(formatAssessment) });
  }));

  // ── Investigation outcomes ──────────────────────────────────
  router.get('/claims/:id/outcomes', limits.read, wrap(async (req, res) => {
    const claimId = parseId(req.params.id, 'claim');
    await requireClaim(claimId);
    const [rows] = await pool.query(
      `SELECT o.*, t.EXCLUSION_REASON, t.IS_TRAINING_ELIGIBLE FROM CLAIM_INVESTIGATION_OUTCOME o
       JOIN OUTCOME_TRAINING_SNAPSHOT t ON t.OUTCOME_ID = o.OUTCOME_ID
       WHERE o.CLAIM_ID = ? ORDER BY o.DECIDED_AT DESC, o.OUTCOME_ID DESC`, [claimId]);
    res.json({ success: true, data: rows.map(formatOutcome) });
  }));

  router.post('/claims/:id/outcomes', requireRole(ROLES.INVESTIGATION), limits.outcome, wrap(async (req, res) => {
    const claimId = parseId(req.params.id, 'claim');
    const b = req.body || {};
    if (TIMESTAMP_FIELDS.some((f) => f in b)) throw new HttpError(400, 'Timestamps are generated by the database and must not be sent');
    if (!OUTCOMES.includes(b.outcome)) throw new HttpError(400, `outcome must be one of: ${OUTCOMES.join(', ')}`);
    if (b.outcome_basis != null && !OUTCOME_BASES.includes(b.outcome_basis)) {
      throw new HttpError(400, `outcome_basis must be one of: ${OUTCOME_BASES.join(', ')}`);
    }
    if (b.notes != null && (typeof b.notes !== 'string' || b.notes.length > 2000)) throw new HttpError(400, 'notes must be text of at most 2000 characters');
    if (b.assessment_id === undefined || b.assessment_id === null || b.assessment_id === '') {
      throw new HttpError(400, 'assessment_id is required: the exact assessment snapshot displayed to the investigator');
    }
    const assessmentId = parseId(b.assessment_id, 'assessment');
    await requireClaim(claimId);

    // Validate the exact supplied snapshot. No other snapshot is ever substituted.
    const [[a]] = await pool.query('SELECT ASSESSMENT_ID, CLAIM_ID, ASSESSMENT_STATUS FROM CLAIM_RISK_ASSESSMENT WHERE ASSESSMENT_ID = ?', [assessmentId]);
    if (!a) throw new HttpError(422, 'Linked assessment does not exist', { reason: 'linked_snapshot_missing' });
    if (a.CLAIM_ID !== claimId) throw new HttpError(422, 'Linked assessment belongs to another claim', { reason: 'linked_snapshot_other_claim' });
    if (a.ASSESSMENT_STATUS === 'failed') throw new HttpError(422, 'Linked assessment is a failed attempt', { reason: 'linked_snapshot_failed' });

    let id;
    try {
      const [r] = await pool.query(
        `INSERT INTO CLAIM_INVESTIGATION_OUTCOME (CLAIM_ID, OUTCOME, OUTCOME_BASIS, NOTES, DECIDED_BY_USER_ID, DECIDED_BY_EMAIL, DECIDED_BY_ROLE, ASSESSMENT_ID)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
        [claimId, b.outcome, b.outcome_basis ?? null, b.notes ?? null, req.user.id, req.user.email, req.user.role, assessmentId]);
      id = r.insertId;
    } catch (e) {
      // Final safeguard: trigger trg_cio_valid_snapshot (SQLSTATE 45000) or CHECK constraints (3819) reject the row.
      if (e && (e.sqlState === '45000' || e.errno === 3819)) throw new HttpError(422, e.sqlMessage || 'Outcome rejected by the database', { reason: 'rejected_by_database' });
      throw e;
    }
    const [[row]] = await pool.query(
      `SELECT o.*, t.EXCLUSION_REASON, t.IS_TRAINING_ELIGIBLE FROM CLAIM_INVESTIGATION_OUTCOME o
       JOIN OUTCOME_TRAINING_SNAPSHOT t ON t.OUTCOME_ID = o.OUTCOME_ID WHERE o.OUTCOME_ID = ?`, [id]);
    const [[linked]] = await pool.query(`${ASSESSMENT_SELECT} WHERE a.ASSESSMENT_ID = ?`, [assessmentId]);
    res.status(201).json({ success: true, data: { ...formatOutcome(row), linked_assessment: {
      assessment_id: linked.ASSESSMENT_ID, assessed_at: linked.ASSESSED_AT, indicators_digest: linked.INDICATORS_DIGEST,
      review_priority: linked.REVIEW_PRIORITY, indicator_set_version: linked.INDICATOR_SET_VERSION } },
    message: 'Outcome recorded. Claim status is not changed by this action.' });
  }));

  // ── Provider profiles ───────────────────────────────────────
  router.get('/providers/:id/profile', ...COMPUTE, wrap(async (req, res) => {
    const providerId = parseId(req.params.id, 'provider');
    const asOf = req.query.as_of;
    if (asOf !== undefined && !(DATE_RE.test(asOf) && !Number.isNaN(Date.parse(`${asOf}T00:00:00Z`)))) {
      throw new HttpError(400, 'as_of must be a date in the form YYYY-MM-DD');
    }
    const [[p]] = await pool.query('SELECT PROVIDER_ID FROM MEDICAL_PROVIDER WHERE PROVIDER_ID = ?', [providerId]);
    if (!p) throw new HttpError(404, 'Provider not found');
    // Effective as-of date: the requested date, or today's IST date on the MySQL clock (never a host's local date).
    // It is always sent explicitly, so Express, FastAPI and any failed row use the same date.
    const asOfSource = asOf ? 'requested' : 'default_today_ist';
    const effectiveAsOf = asOf || (await pool.query(APP_TODAY_SQL))[0][0].d;

    let body;
    try {
      body = await ml.getJson(`/v1/providers/${providerId}/indicators?as_of=${effectiveAsOf}`);
      if (body && body.as_of_date !== effectiveAsOf) throw new MlUnavailableError('bad_response', 'AI service used a different as-of date');
      validateProviderProfile(body, providerId);
    } catch (err) {
      if (err instanceof MlRequestError) throw new HttpError(err.status === 404 ? 404 : 400, err.status === 404 ? 'Provider not found by the AI service' : 'Invalid request');
      if (!(err instanceof MlUnavailableError)) throw err;
      let failedId = null;
      if (!NOT_STORED_REASONS.has(err.reason)) {
        try {
          const [[m]] = await pool.query('SELECT MODEL_ID FROM MODEL_REGISTRY WHERE MODEL_KEY = ? AND APPLIES_TO_LIVE_DATA = 1', [indicatorSetKey]);
          if (m) {
            const [r] = await pool.query(
              `INSERT INTO PROVIDER_RISK_PROFILE (PROVIDER_ID, MODEL_ID, PROFILE_STATUS, AS_OF_DATE, ERROR_MESSAGE)
               VALUES (?, ?, 'failed', ?, ?)`,
              [providerId, m.MODEL_ID, effectiveAsOf, truncate(`${err.reason}: ${err.message}`)]);
            failedId = r.insertId;
          }
        } catch (e) { console.error('[ai] could not record failed profile:', e.message); }
      }
      const [[last]] = await pool.query(
        `${PROFILE_SELECT} WHERE p.PROVIDER_ID = ? AND p.PROFILE_STATUS <> 'failed' ORDER BY p.COMPUTED_AT DESC, p.PROFILE_ID DESC LIMIT 1`, [providerId]);
      throw new HttpError(503, UNAVAILABLE_MESSAGE, { ai_status: 'unavailable', reason: err.reason, failed_attempt_id: failedId,
        as_of_date: effectiveAsOf, as_of_source: asOfSource,
        last_valid_profile: last ? { ...formatProfile(last), stale: true } : null });
    }

    const conn = await pool.getConnection();
    const lockName = `fraud_ai_profile_${providerId}`;
    let locked = false;
    try {
      const [[{ got }]] = await conn.query('SELECT GET_LOCK(?, 5) AS got', [lockName]);
      if (got !== 1) throw new HttpError(503, 'Profile busy, please retry', { ai_status: 'busy' });
      locked = true;
      const model = await resolveModel(conn, body.indicator_set, body.indicator_set_version);
      const indicatorsJson = JSON.stringify(body.indicators);
      // Reuse the latest stored profile if it has identical content for the same as-of date (append-only, no duplicates).
      const [[same]] = await conn.query(
        `SELECT p.PROFILE_ID FROM PROVIDER_RISK_PROFILE p
         WHERE p.PROVIDER_ID = ? AND p.PROFILE_STATUS <> 'failed'
           AND p.PROFILE_ID = (SELECT MAX(q.PROFILE_ID) FROM PROVIDER_RISK_PROFILE q
                               WHERE q.PROVIDER_ID = p.PROVIDER_ID AND q.PROFILE_STATUS <> 'failed' AND q.AS_OF_DATE = p.AS_OF_DATE)
           AND p.MODEL_ID = ? AND p.AS_OF_DATE = ? AND p.PROFILE_STATUS = ? AND p.CLAIM_COUNT = ? AND p.INDICATORS = CAST(? AS JSON)`,
        [providerId, model.MODEL_ID, body.as_of_date, body.profile_status, body.claim_count, indicatorsJson]);
      let id;
      let snapshot;
      if (same) {
        id = same.PROFILE_ID;
        snapshot = 'unchanged';
      } else {
        const [r] = await conn.query(
          `INSERT INTO PROVIDER_RISK_PROFILE (PROVIDER_ID, MODEL_ID, PROFILE_STATUS, AS_OF_DATE, CLAIM_COUNT, INDICATORS)
           VALUES (?, ?, ?, ?, ?, CAST(? AS JSON))`,
          [providerId, model.MODEL_ID, body.profile_status, body.as_of_date, body.claim_count, indicatorsJson]);
        id = r.insertId;
        snapshot = 'new';
      }
      const [[stored]] = await conn.query(`${PROFILE_SELECT} WHERE p.PROFILE_ID = ?`, [id]);
      res.json({ success: true, ai_status: 'available', snapshot, as_of_source: asOfSource, profile: formatProfile(stored),
        comparable_peers: body.comparable_peers, triggered_count: body.triggered_count, disclaimer: body.disclaimer });
    } finally {
      if (locked) await conn.query('SELECT RELEASE_LOCK(?)', [lockName]).catch(() => {});
      conn.release();
    }
  }));

  // ── AI dashboard (stored results only; no ML call) ───────────
  router.get('/dashboard', limits.read, wrap(async (req, res) => {
    const [[totals]] = await pool.query(
      `SELECT (SELECT COUNT(*) FROM CLAIM) AS total_claims,
              (SELECT COUNT(*) FROM CLAIM_LATEST_VALID_ASSESSMENT) AS assessed_claims,
              (SELECT COUNT(*) FROM CLAIM_RISK_ASSESSMENT WHERE ASSESSMENT_STATUS = 'failed'
                 AND ASSESSED_AT >= UTC_TIMESTAMP() - INTERVAL 1 DAY) AS failed_attempts_24h`);
    const [prio] = await pool.query('SELECT REVIEW_PRIORITY AS p, COUNT(*) AS n FROM CLAIM_LATEST_VALID_ASSESSMENT GROUP BY REVIEW_PRIORITY');
    const [queue] = await pool.query(
      `SELECT v.ASSESSMENT_ID, v.CLAIM_ID, v.REVIEW_PRIORITY, v.TRIGGERED_COUNT, v.ASSESSED_AT,
              DATE_FORMAT(c.CLAIM_DATE, '%Y-%m-%d') AS CLAIM_DATE, c.CLAIM_AMOUNT, c.STATUS
       FROM CLAIM_LATEST_VALID_ASSESSMENT v JOIN CLAIM c ON c.CLAIM_ID = v.CLAIM_ID
       WHERE v.REVIEW_PRIORITY IN ('High', 'Elevated')
       ORDER BY FIELD(v.REVIEW_PRIORITY, 'High', 'Elevated'), v.TRIGGERED_COUNT DESC, v.ASSESSED_AT DESC LIMIT 20`);
    const [outcomes] = await pool.query('SELECT OUTCOME AS o, COUNT(*) AS n FROM CLAIM_LATEST_OUTCOME GROUP BY OUTCOME');
    const [[train]] = await pool.query(
      `SELECT COUNT(*) AS eligible_final_outcomes, COALESCE(SUM(t.OUTCOME = 'Confirmed Fraud'), 0) AS eligible_confirmed_fraud
       FROM CLAIM_LATEST_OUTCOME l JOIN OUTCOME_TRAINING_SNAPSHOT t ON t.OUTCOME_ID = l.OUTCOME_ID
       WHERE t.IS_TRAINING_ELIGIBLE = 1`);
    const [[m]] = await pool.query('SELECT MODEL_KEY, VERSION, IS_ACTIVE FROM MODEL_REGISTRY WHERE MODEL_KEY = ?', [indicatorSetKey]);
    // Stored results only (read-only summaries; nothing is computed or written here).
    const [recent] = await pool.query(
      `SELECT v.ASSESSMENT_ID, v.CLAIM_ID, v.REVIEW_PRIORITY, v.TRIGGERED_COUNT, v.INDICATORS, v.RULE_HITS, v.ASSESSED_AT, v.INDICATOR_SET_VERSION
       FROM CLAIM_LATEST_VALID_ASSESSMENT v ORDER BY v.ASSESSED_AT DESC, v.ASSESSMENT_ID DESC LIMIT 10`);
    const [profiles] = await pool.query(
      `SELECT x.PROFILE_ID, x.PROVIDER_ID, mp.PROVIDER_NAME, mp.PROVIDER_TYPE, DATE_FORMAT(x.AS_OF_DATE, '%Y-%m-%d') AS AS_OF_DATE_TEXT,
              x.CLAIM_COUNT, x.PROFILE_STATUS, x.INDICATORS, x.COMPUTED_AT
       FROM (SELECT p.*, ROW_NUMBER() OVER (PARTITION BY p.PROVIDER_ID ORDER BY p.COMPUTED_AT DESC, p.PROFILE_ID DESC) AS RN
             FROM PROVIDER_RISK_PROFILE p WHERE p.PROFILE_STATUS <> 'failed') x
       JOIN MEDICAL_PROVIDER mp ON mp.PROVIDER_ID = x.PROVIDER_ID WHERE x.RN = 1`);
    const [[{ n: providerTotal }]] = await pool.query('SELECT COUNT(*) AS n FROM MEDICAL_PROVIDER');
    const triggeredOf = (inds) => (Array.isArray(inds) ? inds : []).filter((i) => i.triggered === true).map((i) => ({ code: i.code, name: i.name }));
    const providerRows = profiles.map((r) => ({
      profile_id: r.PROFILE_ID, provider_id: r.PROVIDER_ID, provider_name: r.PROVIDER_NAME, provider_type: r.PROVIDER_TYPE,
      as_of_date: r.AS_OF_DATE_TEXT, claim_count: r.CLAIM_COUNT, profile_status: r.PROFILE_STATUS, computed_at: r.COMPUTED_AT,
      triggered_indicators: triggeredOf(r.INDICATORS),
    })).sort((a, b) => b.triggered_indicators.length - a.triggered_indicators.length || b.claim_count - a.claim_count);
    const byPriority = Object.fromEntries(PRIORITIES.map((p) => [p, 0]));
    prio.forEach((r) => { if (r.p) byPriority[r.p] = Number(r.n); });
    const byOutcome = Object.fromEntries(OUTCOMES.map((o) => [o, 0]));
    outcomes.forEach((r) => { byOutcome[r.o] = Number(r.n); });
    res.json({
      success: true,
      indicator_set: m ? { model_key: m.MODEL_KEY, version: m.VERSION, active: m.IS_ACTIVE === 1 } : null,
      ml_service: ml.status(),
      claims: { total: Number(totals.total_claims), with_valid_assessment: Number(totals.assessed_claims),
        failed_attempts_last_24h: Number(totals.failed_attempts_24h) },
      review_priority: byPriority,
      review_queue: queue.map((q) => ({ assessment_id: q.ASSESSMENT_ID, claim_id: q.CLAIM_ID, review_priority: q.REVIEW_PRIORITY,
        triggered_count: q.TRIGGERED_COUNT, assessed_at: q.ASSESSED_AT, claim_date: q.CLAIM_DATE, claim_amount: Number(q.CLAIM_AMOUNT),
        claim_status: q.STATUS })),
      recent_assessments: recent.map((r) => ({ assessment_id: r.ASSESSMENT_ID, claim_id: r.CLAIM_ID, review_priority: r.REVIEW_PRIORITY,
        triggered_count: r.TRIGGERED_COUNT, rule_hit_count: Array.isArray(r.RULE_HITS) ? r.RULE_HITS.length : 0,
        triggered_indicators: triggeredOf(r.INDICATORS), indicator_set_version: r.INDICATOR_SET_VERSION, assessed_at: r.ASSESSED_AT })),
      provider_overview: {
        total_providers: Number(providerTotal),
        profiled_providers: providerRows.length,
        with_triggered_indicators: providerRows.filter((p) => p.triggered_indicators.length > 0).length,
        insufficient_data: providerRows.filter((p) => p.profile_status === 'insufficient_data').length,
        providers: providerRows.slice(0, 10),
      },
      latest_outcomes: byOutcome,
      future_supervised_model: {
        eligible_final_outcomes: Number(train.eligible_final_outcomes),
        eligible_confirmed_fraud: Number(train.eligible_confirmed_fraud),
        review_checkpoint: { final_outcomes: 200, confirmed_fraud: 30 },
        note: 'Reaching the checkpoint triggers a review of label quality, balance and validation; it is not permission to train.',
      },
      note: 'Review priority is an ordering aid, not a score or a decision. It never changes claim status.',
    });
  }));

  // ── Research (public Kaggle data only; never applied to application data) ──
  async function research(res, path) {
    try {
      res.json({ success: true, ...(await ml.getJson(path)) });
    } catch (err) {
      if (err instanceof MlRequestError) throw new HttpError(err.status === 404 ? 404 : 400, err.message);
      if (err instanceof MlUnavailableError) throw new HttpError(503, 'Research results unavailable (AI service)', { ai_status: 'unavailable', reason: err.reason });
      throw err;
    }
  }

  router.get('/research/models', limits.read, wrap((req, res) => research(res, '/v1/research/models')));
  router.get('/research/shap/global', limits.read, wrap((req, res) => research(res, '/v1/research/shap/global')));
  router.get('/research/providers/:kaggleId/explanation', limits.read, wrap((req, res) => {
    if (!KAGGLE_ID_RE.test(req.params.kaggleId)) {
      throw new HttpError(400, 'Research explanations exist only for Kaggle provider IDs of the form PRV00000 (not application providers)');
    }
    return research(res, `/v1/research/providers/${req.params.kaggleId}/explanation`);
  }));
  router.get('/research/figures/:name', limits.read, wrap(async (req, res) => {
    if (!FIGURE_RE.test(req.params.name)) throw new HttpError(400, 'Invalid figure name');
    try {
      const f = await ml.getBinary(`/v1/research/figures/${req.params.name}`);
      if (f.contentType !== 'image/png') throw new MlUnavailableError('bad_response', 'unexpected figure type');
      res.set({ 'Content-Type': 'image/png', 'Cache-Control': 'private, max-age=300', 'X-Content-Type-Options': 'nosniff' }).send(f.body);
    } catch (err) {
      if (err instanceof MlRequestError) throw new HttpError(err.status === 404 ? 404 : 400, 'Figure not found');
      if (err instanceof MlUnavailableError) throw new HttpError(503, 'Research figure unavailable (AI service)', { ai_status: 'unavailable', reason: err.reason });
      throw err;
    }
  }));

  return router;
}

